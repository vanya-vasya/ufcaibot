import React from "react";
import { Document, Page, Text, View, StyleSheet, Image } from "@react-pdf/renderer";

export interface AnalysisReportSection {
  heading: string;
  text: string;
}

interface AnalysisReportProps {
  fighterA: string;
  fighterB: string;
  /** Product name shown under the title, e.g. "ULTIMATE". */
  productLabel?: string;
  /** ISO timestamp of the analysis. */
  timestamp: string;
  sections: AnalysisReportSection[];
  /** Logo URL. Pass null to render without a logo. */
  logoSrc?: string | null;
}

const colors = {
  ink: "#111111",
  muted: "#687385",
  rule: "#e6ebf1",
  accent: "#dc2626",
};

const styles = StyleSheet.create({
  page: {
    padding: 40,
    fontSize: 12,
    fontFamily: "Helvetica",
    color: colors.ink,
    backgroundColor: "#ffffff",
  },
  header: { alignItems: "center", marginBottom: 24 },
  logo: { width: 72, height: 72, objectFit: "contain", marginBottom: 12 },
  title: { fontSize: 22, fontFamily: "Helvetica-Bold", textAlign: "center" },
  subtitle: { marginTop: 6, fontSize: 11, color: colors.muted, textAlign: "center" },
  section: { marginTop: 22, paddingTop: 14, borderTopWidth: 1, borderTopColor: colors.rule },
  sectionHeading: {
    fontSize: 11,
    fontFamily: "Helvetica-Bold",
    letterSpacing: 1,
    color: colors.accent,
    marginBottom: 8,
  },
  sectionText: { fontSize: 13, lineHeight: 1.5 },
  footer: {
    position: "absolute",
    left: 40,
    right: 40,
    bottom: 28,
    fontSize: 9,
    color: colors.muted,
    textAlign: "center",
  },
});

const formatDate = (timestamp: string) =>
  new Date(timestamp).toLocaleDateString("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });

const AnalysisReport = ({
  fighterA,
  fighterB,
  productLabel,
  timestamp,
  sections,
  logoSrc = "/logos/ufc-fighter-logo.png",
}: AnalysisReportProps) => (
  <Document title={`${fighterA} vs ${fighterB} - ufcaibot analysis`} author="ufcaibot">
    <Page size="A4" style={styles.page}>
      <View style={styles.header}>
        {/* eslint-disable-next-line jsx-a11y/alt-text */}
        {logoSrc ? <Image src={logoSrc} style={styles.logo} /> : null}
        <Text style={styles.title}>
          {fighterA.toUpperCase()} VS {fighterB.toUpperCase()}
        </Text>
        <Text style={styles.subtitle}>
          {[productLabel ? `${productLabel} analysis` : "Analysis", formatDate(timestamp)].join(
            "  |  "
          )}
        </Text>
      </View>

      {sections.map(({ heading, text }) => (
        <View key={heading} style={styles.section} wrap={false}>
          <Text style={styles.sectionHeading}>{heading}</Text>
          <Text style={styles.sectionText}>{text}</Text>
        </View>
      ))}

      <Text style={styles.footer} fixed>
        Analysis generated by ufcaibot | ufcaibot.com | For entertainment purposes only
      </Text>
    </Page>
  </Document>
);

export default AnalysisReport;
